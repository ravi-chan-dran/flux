// Mock EventSource for SSE
global.EventSource = class EventSource {
  constructor(url) {
    this.url = url
    this.readyState = 1
    this.onopen = null
    this.onmessage = null
    this.onerror = null
  }
  
  addEventListener(event, handler) {
    if (event === 'open') this.onopen = handler
    if (event === 'message') this.onmessage = handler
    if (event === 'error') this.onerror = handler
  }
  
  removeEventListener() {}
  
  close() {
    this.readyState = 2
  }
}

